/**
 * Schema v1 — Competition/Season statistics, match details, ticketing, payments.
 * Additive only. Existing community collections are never touched.
 *
 * Permission model:
 *  - PUBLIC collections: read("any") only. No client create/update/delete — the server function writes them.
 *  - PRIVATE collections: no collection-level grants, documentSecurity=true. The server grants read("user:<id>")
 *    on documents the owner may see. Append-only audit collections never get update/delete grants.
 */

